-- Compras de fornecedor (Purchases), estoque de sobras (Stock) e
-- e-mail do resumo semanal. Rodar uma vez (o app também funciona sem o
-- SUMMARY_EMAIL — usa o e-mail da empresa).

CREATE TABLE IF NOT EXISTS purchases (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  SUPPLIER VARCHAR(100) NOT NULL,
  ORDER_NUMBER VARCHAR(50) DEFAULT NULL,
  PURCHASE_DATE DATE NOT NULL,
  JOB_PROJECT_ID INT DEFAULT NULL,
  RECEIPT_PATH VARCHAR(500) DEFAULT NULL,
  TAX_AMOUNT DECIMAL(10,2) NOT NULL DEFAULT 0,
  TOTAL_AMOUNT DECIMAL(12,2) NOT NULL DEFAULT 0,
  EXPENSE_ID INT DEFAULT NULL,
  NOTES VARCHAR(255) DEFAULT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  KEY idx_purchases_job (JOB_PROJECT_ID),
  CONSTRAINT fk_purchases_job FOREIGN KEY (JOB_PROJECT_ID) REFERENCES job_projects (ID) ON DELETE SET NULL,
  CONSTRAINT fk_purchases_expense FOREIGN KEY (EXPENSE_ID) REFERENCES expenses (ID) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS purchase_items (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  PURCHASE_ID INT NOT NULL,
  PRODUCT_ID INT NOT NULL,
  QUANTITY DECIMAL(10,2) NOT NULL,
  UNIT_PRICE DECIMAL(10,2) NOT NULL DEFAULT 0,
  TO_STOCK TINYINT(1) NOT NULL DEFAULT 0,
  CONSTRAINT fk_pitems_purchase FOREIGN KEY (PURCHASE_ID) REFERENCES purchases (ID) ON DELETE CASCADE,
  CONSTRAINT fk_pitems_product FOREIGN KEY (PRODUCT_ID) REFERENCES products (ID)
);

-- Cada linha é um movimento: + entra no estoque (sobra/compra), - sai (usado num job)
CREATE TABLE IF NOT EXISTS inventory_moves (
  ID INT AUTO_INCREMENT PRIMARY KEY,
  PRODUCT_ID INT NOT NULL,
  QUANTITY DECIMAL(10,2) NOT NULL,
  UNIT_PRICE DECIMAL(10,2) NOT NULL DEFAULT 0,
  JOB_PROJECT_ID INT DEFAULT NULL,
  NOTE VARCHAR(255) DEFAULT NULL,
  CREATED_BY VARCHAR(50) DEFAULT NULL,
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  KEY idx_inv_product (PRODUCT_ID),
  CONSTRAINT fk_inv_product FOREIGN KEY (PRODUCT_ID) REFERENCES products (ID),
  CONSTRAINT fk_inv_job FOREIGN KEY (JOB_PROJECT_ID) REFERENCES job_projects (ID) ON DELETE SET NULL
);
